// Writes the exercise list the AI program builder may use
// (supabase/functions/ai/exercises.ts) from the app's own catalogue: every
// exercise the picker offers (retired ones left out), with its muscle and
// equipment. The Edge Function can't read the app's files, so it gets its own
// copy; scripts/verify-ai.ts fails while the two differ.
//
//   npx tsx scripts/build-ai-exercises.ts   (after node scripts/build-exercises.mjs)

import { EXERCISES } from "../constants/exerciseData";
import { aiExerciseLines } from "./harness/aiExercises";

declare const __dirname: string;
// eslint-disable-next-line @typescript-eslint/no-require-imports -- no @types/node in the app
const { writeFileSync } = require("node:fs") as { writeFileSync(file: string, data: string): void };

const lines = aiExerciseLines(EXERCISES);
writeFileSync(
  `${__dirname}/../supabase/functions/ai/exercises.ts`,
  `// AUTO-GENERATED by scripts/build-ai-exercises.ts. Do not edit by hand.\n` +
  `// Every exercise the app's picker offers, as "Name | muscle | equipment": the\n` +
  `// only names the program builder may use (supabase/functions/ai/prompts.ts).\n\n` +
  `export const AI_EXERCISES: readonly string[] = ${JSON.stringify(lines, null, 2)};\n`,
);
console.log(`✓ ${lines.length} exercises  →  supabase/functions/ai/exercises.ts`);
